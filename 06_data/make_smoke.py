def build(s):
    output = (f'【解决问题的思路及措施】\n{s["思路措施"]}\n\n'
              f'【标准沟通话术】\n{s["标准话术"]}')
    lines = [f'目录：{s["目录"]}']
    for f in ('事业部', '一级行业', '二级行业', '三级行业', '产品大类',
              '问题类型', '适用背景', '问题'):
        if s.get(f):
            lines.append(f'{f}：{s[f]}')
    facts = extract_facts(output)
    lines.append('\n【可用事实】')
    lines.extend(f'- [{k}] {v}' for v, k in facts) if facts else lines.append('- （无）')
    return {'instruction': INSTRUCTION, 'input': '\n'.join(lines), 'output': output}, facts


